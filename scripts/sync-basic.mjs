import { basicCatalog } from '@a2ui/web_core/catalogs/basic/v1';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve('a2ui-catalog/basic/catalog.json');
mkdirSync(resolve('a2ui-catalog/basic'), { recursive: true });
const source = basicCatalog.toJson();
writeFileSync(target, JSON.stringify(source, null, 2) + '\n');
console.log(`Copied SDK Basic Catalog: ${Object.keys(source.components).length} components, ${Object.keys(source.functions).length} functions -> ${target}`);
console.log('Source: installed @a2ui/web_core. This file was NOT generated by the Storybook exporter.');
