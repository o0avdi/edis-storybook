// Presenter-friendly JSON viewer for the three kinds of catalog, each labeled with its provenance.
//
//   npm run catalog:show                          overview of what exists
//   npm run catalog:show -- ProgressIndicator     one EXPORTED component schema
//   npm run catalog:show -- --single              the complete one-component exported catalog
//   npm run catalog:show -- --extension           the complete multi-component exported catalog
//   npm run catalog:show -- --report              exporter report summary (exported / blocked)
//   npm run catalog:show -- --official [Name]     the OFFICIAL SDK Basic Catalog, or one official component
//
// Reads fresh output from a2ui-catalog/ when present; otherwise falls back to the committed snapshots in
// catalog-snapshots/ and says so in the header.
import { existsSync, readFileSync } from 'node:fs';
import { EXPORTS, OFFICIAL, SNAPSHOT_ROOT } from './catalog-config.mjs';

const [first, second] = process.argv.slice(2);

// Presenter-facing tool: print a readable message instead of a stack trace.
process.on('uncaughtException', (error) => {
  console.error(error.message);
  process.exit(1);
});

function load(freshDir, snapshotKey, file) {
  const fresh = `${freshDir}/${file}`;
  const snapshot = `${SNAPSHOT_ROOT}/${snapshotKey}/${file}`;
  if (existsSync(fresh)) return { json: JSON.parse(readFileSync(fresh, 'utf8')), source: `${fresh}  [fresh output]` };
  if (existsSync(snapshot)) return { json: JSON.parse(readFileSync(snapshot, 'utf8')), source: `${snapshot}  [PRE-GENERATED SNAPSHOT]` };
  throw new Error(`Neither ${fresh} nor ${snapshot} exists. Run "npm run demo:export".`);
}

function header(title, source) {
  const line = '-'.repeat(Math.min(100, Math.max(title.length, source.length) + 8));
  console.log(`${line}\n${title}\nsource: ${source}\n${line}`);
}
const print = (value) => console.log(JSON.stringify(value, null, 2));

const official = () => load(OFFICIAL.dir, OFFICIAL.key, 'catalog.json');
const extension = () => load(EXPORTS.extension.out, EXPORTS.extension.key, 'catalog.json');

if (!first) {
  const { json: ext, source: extSource } = extension();
  const { json: off, source: offSource } = official();
  console.log('Catalogs available (each labeled with where its JSON came from):\n');
  console.log(`EXPORTED by storybook-a2ui   ${Object.keys(ext.components).join(', ')}\n  ${extSource}`);
  console.log(`OFFICIAL SDK Basic Catalog   ${Object.keys(off.components).length} components\n  ${offSource}`);
  console.log('\nTry: npm run catalog:show -- ProgressIndicator | --single | --extension | --report | --official Button');
} else if (first === '--official') {
  const { json, source } = official();
  if (second) {
    if (!json.components[second]) throw new Error(`${second} is not an official Basic Catalog component.`);
    header(`OFFICIAL Basic Catalog component "${second}" (SDK-authored, NOT exporter output)`, source);
    print(json.components[second]);
  } else {
    header('OFFICIAL A2UI Basic Catalog (SDK-authored via basicCatalog.toJson(), NOT exporter output)', source);
    print(json);
  }
} else if (first === '--extension') {
  const { json, source } = extension();
  header(`EXPORTED extension catalog: ${Object.keys(json.components).join(', ')}`, source);
  print(json);
} else if (first === '--single') {
  const { json, source } = load(EXPORTS.single.out, EXPORTS.single.key, 'catalog.json');
  header(`EXPORTED one-component catalog: ${Object.keys(json.components).join(', ')}`, source);
  print(json);
} else if (first === '--report') {
  const { json, source } = load(EXPORTS.extension.out, EXPORTS.extension.key, 'export-report.json');
  header(`Exporter report: result=${json.result}, validation=${json.validation?.valid ? 'PASS' : 'FAIL'}, policy=${JSON.stringify(json.policy)}`, source);
  for (const entry of json.components) {
    console.log(`${entry.status.toUpperCase().padEnd(9)}${entry.name.padEnd(20)}${entry.properties.join(', ')}`);
    for (const issue of entry.blocking) console.log(`          ${issue.code}: ${issue.message}`);
  }
  console.log(`\nnotice: ${json.notice}`);
} else {
  const { json, source } = extension();
  if (!json.components[first]) {
    throw new Error(`"${first}" is not in the exported extension catalog (${Object.keys(json.components).join(', ')}). ` +
      'For SDK components use: npm run catalog:show -- --official <Name>');
  }
  header(`EXPORTED component "${first}" (generated by storybook-a2ui from Storybook metadata)`, source);
  print(json.components[first]);
}
