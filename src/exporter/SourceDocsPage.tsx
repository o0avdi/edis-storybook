import { Controls, Description, Heading, Primary, Stories, Subtitle, Title, Unstyled, useOf } from '@storybook/addon-docs/blocks';
import { JsonView } from '../basic/JsonView';
import { SchemaTable } from '../basic/SchemaTable';
import { exportedComponent } from './snapshots';

/**
 * Docs page for a React source primitive that our exporter converts. Unlike the SDK pages, the
 * controls here ARE generated from the component's real props (react-docgen), the same metadata
 * Storybook writes to manifests/components.json for the exporter.
 */
export function SourceDocsPage() {
  const resolved = useOf('meta');
  // Explicit parameter rather than `component.name`, which minification renames in static builds.
  const name = (resolved.type === 'meta' ? resolved.preparedMeta.parameters?.exportedAs : undefined) as string | undefined;
  const schema = name ? exportedComponent(name) : undefined;
  return (
    <>
      <Title />
      <Subtitle>React source primitive · exported to A2UI by storybook-a2ui</Subtitle>
      <Description />
      <div className="docs-callout docs-callout--source">
        <strong>Different from the Basic Catalog pages.</strong> This is a real React component in{' '}
        <code>src/extensions/</code>. Its controls are generated by Storybook from the TypeScript props (react-docgen),
        and the same metadata lands in <code>storybook-static/manifests/components.json</code>, which the exporter reads.
        It is <em>not</em> registered as an A2UI renderer component; this project stops at a validated schema.
      </div>
      <Primary />
      <Heading>Props (from Storybook docgen)</Heading>
      <Controls />
      <Heading>Exported A2UI schema · {name}</Heading>
      {schema ? (
        <>
          <p className="docs-note">
            <strong>Pre-generated snapshot</strong> from <code>catalog-snapshots/extension/catalog.json</code>, copied from a
            real <code>storybook-a2ui export</code> run. Regenerate with <code>npm run demo:export</code> then{' '}
            <code>npm run catalog:snapshot</code>; <code>npm run catalog:verify</code> fails if it drifts.
          </p>
          <Unstyled>
            <SchemaTable schema={schema} />
            <div style={{ marginTop: 16 }}>
              <JsonView value={schema} title={`components.${name}`} caption="exporter output · pre-generated snapshot" />
            </div>
          </Unstyled>
        </>
      ) : (
        <p className="docs-note">
          No snapshot for {name} yet. Run <code>npm run demo:export</code> and <code>npm run catalog:snapshot</code>.
        </p>
      )}
      <Stories title="Named variants" includePrimary={false} />
    </>
  );
}
