// Read-only tools for the two FROZEN example catalogs in demo-examples/. Nothing here writes to disk.
//
//   npm run examples:verify      checks both files are unchanged (SHA-256) and still valid exporter catalogs
//   npm run examples:show        lists both examples
//   npm run examples:show -- 1   prints example 1 (ProgressIndicator only)
//   npm run examples:show -- 2   prints example 2 (StatusBadge, MetricLabel, ProgressIndicator)
//
// To intentionally replace an example (not needed for the showcase): copy a new, verified exporter output over the
// file by hand and update its hash below in the same commit.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';

const OFFICIAL_CATALOG_ID = 'https://a2ui.org/specification/v1_0/catalogs/basic/catalog.json';

const EXAMPLES = [
  {
    key: '1',
    file: 'demo-examples/01-single-component/catalog.json',
    title: 'Example 1: single-component catalog (ProgressIndicator)',
    components: ['ProgressIndicator'],
    sha256: 'ce91ee5baf3cd40db36f9656a44093c6ebc5548a1e43be5b9c182c718fda23f9',
  },
  {
    key: '2',
    file: 'demo-examples/02-full-exported-catalog/catalog.json',
    title: 'Example 2: full exported catalog (StatusBadge, MetricLabel, ProgressIndicator)',
    components: ['MetricLabel', 'ProgressIndicator', 'StatusBadge'],
    sha256: '8599d65be926be046251b38676d0f0c8fe3d1bbf09fc3980e17889eb63bb290d',
  },
];

const mode = process.argv[2] ?? 'show';
const choice = process.argv[3];

if (mode === 'verify') await verify();
else if (mode === 'show') show(choice);
else {
  console.error(`Unknown mode "${mode}". Use "verify" or "show".`);
  process.exit(2);
}

async function verify() {
  // The schema check uses the exporter's own validator when it is installed; the hash check needs nothing.
  let validateV1Export;
  try {
    ({ validateV1Export } = await import('storybook-a2ui/src/a2ui/validate.mjs'));
  } catch {
    console.log('NOTE  storybook-a2ui is not installed; skipping the A2UI v1.0 schema check (hash checks still run).');
  }

  let failed = false;
  for (const example of EXAMPLES) {
    const problems = [];
    if (!existsSync(example.file)) {
      problems.push('file is missing');
    } else {
      const bytes = readFileSync(example.file);
      const hash = createHash('sha256').update(bytes).digest('hex');
      if (hash !== example.sha256) problems.push(`SHA-256 changed (expected ${example.sha256}, found ${hash})`);
      try {
        const catalog = JSON.parse(bytes.toString('utf8'));
        const names = Object.keys(catalog.components ?? {}).sort();
        if (names.join() !== example.components.join()) problems.push(`components are ${names.join(', ')}`);
        if (catalog.catalogId === OFFICIAL_CATALOG_ID) problems.push('uses the official Basic Catalog id');
        if (validateV1Export) validateV1Export(catalog); // throws if the catalog no longer validates
      } catch (error) {
        problems.push(error.message);
      }
    }
    if (problems.length) {
      failed = true;
      console.log(`FAIL  ${example.file}\n      ${problems.join('\n      ')}`);
    } else {
      console.log(`PASS  ${example.file}  unchanged, ${example.components.join(', ')}${validateV1Export ? ', valid A2UI v1.0 catalog' : ''}`);
    }
  }
  if (failed) {
    console.log('\nA frozen example changed. Restore it with:  git checkout -- demo-examples');
    process.exit(1);
  }
}

function show(key) {
  if (!key) {
    console.log('Frozen exporter examples (pre-generated by storybook-a2ui; never overwritten by any script):\n');
    for (const example of EXAMPLES) console.log(`  ${example.key}. ${example.title}\n     ${example.file}`);
    console.log('\nPrint one with:  npm run examples:show -- 1   (or 2)');
    console.log('These are NOT the official A2UI Basic Catalog (18 SDK components); see the Storybook explorer for that.');
    return;
  }
  const example = EXAMPLES.find((entry) => entry.key === key);
  if (!example) {
    console.error(`Unknown example "${key}". Use 1 or 2.`);
    process.exit(2);
  }
  const line = '-'.repeat(80);
  console.log(`${line}\n${example.title}\nsource: ${example.file}  [FROZEN EXAMPLE]\n${line}`);
  console.log(readFileSync(example.file, 'utf8'));
}
